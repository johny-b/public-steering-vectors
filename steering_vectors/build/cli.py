"""Focused command-line entry point for capture-only vector construction."""

from __future__ import annotations

import argparse
import tempfile
from pathlib import Path
from typing import Sequence

from .. import vectorfmt
from ..core import canonjson, modelprofile, paths
from . import capture, derive, prompts

PROFILE = modelprofile.PROFILE


def parser() -> argparse.ArgumentParser:
    command = argparse.ArgumentParser(
        prog="build-steering-vector",
        description=(
            "Capture Qwen3.6-27B block-input residuals for two JSONL prompt "
            "sets and write their positive-minus-negative mean."
        ),
    )
    command.add_argument("--positive", required=True, metavar="PATH")
    command.add_argument("--negative", required=True, metavar="PATH")
    command.add_argument("--layer", required=True, type=int, metavar="N")
    command.add_argument("--name", required=True)
    command.add_argument("--description", required=True)
    command.add_argument("--id", dest="vector_id", type=int)
    command.add_argument("--model", default=PROFILE.model_id)
    command.add_argument("--max-model-len", type=int, default=4096)
    command.add_argument(
        "--vectors-dir",
        type=Path,
        default=None,
        help="output root (default: repository vectors/)",
    )
    return command


def _write_index(root: Path) -> Path:
    """Regenerate the retained index shape from validated vector metadata."""
    rows = []
    for vector_id in vectorfmt.existing_ids(root):
        vdir = root / vector_id
        meta = vectorfmt.read_meta(vdir)
        description = " ".join(meta["description"].split())
        if len(description) > 60:
            description = description[:59].rstrip() + "…"
        checked = (
            "yes"
            if None not in vectorfmt.per_prompt_verification(meta).values()
            else "—"
        )
        demo = "yes" if vectorfmt.has_demo(vdir) else "—"
        rows.append(
            f"| `{meta['id_str']}` | **{meta['name']}** | {meta['layer']} | "
            f"{meta['n_pos']}/{meta['n_neg']} | {meta['vector_norm']:.3f} | "
            f"{meta['activation_norm_at_layer']:.2f} | "
            f"{meta['vector_norm_over_activation_norm']:.4f} | {checked} | {demo} | "
            f"{meta['created_at']} | {description} |"
        )
    text = "\n".join(
        [
            "# steering vectors",
            "",
            "One self-describing directory per vector.",
            "",
            "Generated by `build-steering-vector` — every column is read from each "
            "vector's validated `meta.json`.",
            "",
            "| id | name | layer | n pos/neg | `‖v‖` | act. norm | `‖v‖`/act | "
            "capture checked | demo | created | description |",
            "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
            *(rows or ["| — | _no vectors_ | | | | | | | | | |"]),
            "",
            "`‖v‖` and `act. norm` are at the designated layer. The ratio is the "
            "fraction of a typical residual-stream magnitude that raw strength "
            "1.0 adds.",
            "",
            "`capture checked` means both sides record per-prompt verification; "
            "`—` means no claim was recorded.",
            "",
        ]
    )
    return canonjson.write_text_atomic(root / vectorfmt.INDEX_NAME, text)


def build(args: argparse.Namespace) -> Path:
    """Run both capture sides and write one new, non-overwriting vector id."""
    PROFILE.check_layer(args.layer)
    if args.model != PROFILE.model_id:
        raise ValueError(
            f"this builder is profiled only for {PROFILE.model_id!r}, got {args.model!r}"
        )
    positive_prompts = prompts.read_prompt_jsonl(args.positive)
    negative_prompts = prompts.read_prompt_jsonl(args.negative)
    root = args.vectors_dir or paths.vectors_dir()
    vector_id = (
        derive.next_free_id(root) if args.vector_id is None else args.vector_id
    )
    destination = root / vectorfmt.vector_id(vector_id)
    if destination.exists():
        raise vectorfmt.VectorFormatError(
            f"{destination} already exists; vector ids are never overwritten"
        )

    work_root = paths.ensure_dir(paths.repo_root() / ".work")
    work = Path(
        tempfile.mkdtemp(prefix=f"vector-{int(vector_id):04d}-", dir=work_root)
    )
    announce = lambda line: print(line, flush=True)
    positive_mean, positive_report = capture.capture_side(
        positive_prompts,
        work,
        "positive",
        model=args.model,
        max_model_len=args.max_model_len,
        announce=announce,
    )
    negative_mean, negative_report = capture.capture_side(
        negative_prompts,
        work,
        "negative",
        model=args.model,
        max_model_len=args.max_model_len,
        announce=announce,
    )
    written = derive.write_vector_directory(
        vector_id=vector_id,
        name=args.name,
        description=args.description,
        model=args.model,
        layer=args.layer,
        positive_source=args.positive,
        negative_source=args.negative,
        positive=positive_mean,
        negative=negative_mean,
        positive_capture=positive_report,
        negative_capture=negative_report,
        vectors_dir=root,
    )
    _write_index(root)
    return written


def main(argv: Sequence[str] | None = None) -> int:
    args = parser().parse_args(argv)
    print(build(args))
    return 0
